// The Cockpit must load its schedule even when external website scripts are blocked or stale.
const fs=require('node:fs'),path=require('node:path');
const source=['site-data.js','calendar-data.js'].map(name=>fs.readFileSync(path.join(__dirname,'../assets/js',name),'utf8')).join('\n');
fs.writeFileSync(path.join(__dirname,'calendar-runtime.mjs'),'// Generated by build-calendar-runtime.cjs from the shared website schedule and model.\nexport default '+JSON.stringify(source)+';\n');
